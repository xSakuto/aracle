-- Kleinere Dashboard-Lücken: Verlauf bei Anfragen, letzter Login im Team.

-- ─────────────────────────────────────────────
-- Verlauf bei Anfragen (wer hat was wann gemacht)
-- ─────────────────────────────────────────────

create table if not exists public.inquiry_events (
  id          bigint generated by default as identity primary key,
  inquiry_id  uuid not null references public.inquiries (id) on delete cascade,
  actor_id    uuid references public.profiles (id) on delete set null,
  actor_name  text not null default '',
  action      text not null check (action in ('zugewiesen', 'in_inbox', 'archiviert', 'wiederhergestellt', 'notiz')),
  detail      text not null default '',
  created_at  timestamptz not null default now()
);

create index if not exists inquiry_events_inquiry_idx on public.inquiry_events (inquiry_id, created_at desc);

alter table public.inquiry_events enable row level security;

drop policy if exists "events lesen" on public.inquiry_events;
create policy "events lesen" on public.inquiry_events
  for select using (public.has_permission('anfragen'));

drop policy if exists "events schreiben" on public.inquiry_events;
create policy "events schreiben" on public.inquiry_events
  for insert to authenticated with check (public.has_permission('anfragen'));

revoke all on public.inquiry_events from anon;

-- ─────────────────────────────────────────────
-- Letzter Login fürs Team verwalten (nur Admins)
-- ─────────────────────────────────────────────

create or replace function public.team_logins()
returns table (profile_id uuid, last_sign_in_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'forbidden';
  end if;
  return query
    select p.id, u.last_sign_in_at
    from public.profiles p
    join auth.users u on u.id = p.user_id;
end;
$$;

revoke all on function public.team_logins() from public, anon;
grant execute on function public.team_logins() to authenticated;
