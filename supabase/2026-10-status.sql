-- Oktober 2026: Statusseite und Ausfall-Alarm.
-- Einmal im Supabase SQL-Editor ausführen. Rein additiv.
--
-- So läuft es:
--   1. pg_cron ruft jede Minute https://aracle.ch/api/status/run auf (über pg_net),
--      mit einem Geheimnis aus bot_secrets ('status_cron').
--   2. Die Website prüft alle Dienste und meldet das Ergebnis an record_status_run().
--   3. Die Funktion speichert die Prüfung, führt die Tagesstatistik und öffnet oder
--      schliesst Störungen. Zurück kommt, wo sich etwas geändert hat, und die Website
--      verschickt dafür den Alarm (Mail, WhatsApp, Push).

create extension if not exists pg_net with schema extensions;
create extension if not exists pg_cron;

-- Geheimnis für den Aufruf, einmalig zufällig erzeugt
insert into public.bot_secrets (key, value)
values ('status_cron', replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''))
on conflict (key) do nothing;

-- ─────────────────────────────────────────────
-- Tabellen
-- ─────────────────────────────────────────────

-- Einzelne Prüfungen, werden nach 14 Tagen gelöscht
create table if not exists public.status_checks (
  id          bigint generated by default as identity primary key,
  service     text not null check (char_length(service) <= 40),
  ok          boolean not null,
  latency_ms  integer,
  detail      text not null default '' check (char_length(detail) <= 300),
  checked_at  timestamptz not null default now()
);
create index if not exists status_checks_service_idx on public.status_checks (service, checked_at desc);

-- Pro Dienst und Tag zusammengefasst, für die 90-Tage-Leiste
create table if not exists public.status_daily (
  service     text not null,
  day         date not null,
  checks      integer not null default 0,
  ok_checks   integer not null default 0,
  latency_sum bigint not null default 0,
  primary key (service, day)
);

-- Störungen: offen, solange resolved_at leer ist
create table if not exists public.status_incidents (
  id           bigint generated by default as identity primary key,
  service      text not null,
  started_at   timestamptz not null,
  resolved_at  timestamptz,
  detail       text not null default '',
  -- Optionaler Hinweis von Hand, erscheint auf der Statusseite
  note         text not null default '' check (char_length(note) <= 500)
);
create index if not exists status_incidents_service_idx on public.status_incidents (service, started_at desc);
create unique index if not exists status_incidents_one_open on public.status_incidents (service) where resolved_at is null;

alter table public.status_checks enable row level security;
alter table public.status_daily enable row level security;
alter table public.status_incidents enable row level security;

-- Lesen darf jede:r (die Statusseite ist öffentlich), schreiben nur die Funktion unten.
drop policy if exists "status lesen" on public.status_checks;
create policy "status lesen" on public.status_checks for select using (true);
drop policy if exists "status lesen" on public.status_daily;
create policy "status lesen" on public.status_daily for select using (true);
drop policy if exists "störungen lesen" on public.status_incidents;
create policy "störungen lesen" on public.status_incidents for select using (true);
drop policy if exists "störungen notiz" on public.status_incidents;
create policy "störungen notiz" on public.status_incidents
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

grant select on public.status_checks, public.status_daily, public.status_incidents to anon, authenticated;

-- ─────────────────────────────────────────────
-- Funktionen
-- ─────────────────────────────────────────────

create or replace function public.status_secret_ok(p_secret text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select p_secret is not null and length(p_secret) >= 32
     and exists (select 1 from public.bot_secrets where key = 'status_cron' and value = p_secret);
$$;

-- Das Bot-Geheimnis für den signierten Health-Check, nur gegen das Status-Geheimnis
create or replace function public.status_bot_secret(p_secret text)
returns text
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.status_secret_ok(p_secret) then raise exception 'forbidden'; end if;
  return (select value from public.bot_secrets where key = 'site_api');
end;
$$;

-- Ergebnisse speichern. p_results: [{ "service": "...", "ok": true, "latency_ms": 120, "detail": "..." }]
-- p_fails: nach so vielen Fehlschlägen in Folge wird eine Störung eröffnet.
-- Rückgabe: [{ "service", "event": "down" | "up", "started_at", "resolved_at", "detail" }]
create or replace function public.record_status_run(p_secret text, p_results jsonb, p_fails integer default 2)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  r jsonb;
  v_service text;
  v_ok boolean;
  v_latency integer;
  v_detail text;
  v_open public.status_incidents;
  v_recent_fails integer;
  v_first_fail timestamptz;
  v_events jsonb := '[]'::jsonb;
  v_day date := (now() at time zone 'Europe/Zurich')::date;
begin
  if not public.status_secret_ok(p_secret) then raise exception 'forbidden'; end if;

  for r in select * from jsonb_array_elements(p_results) loop
    v_service := left(r->>'service', 40);
    v_ok := coalesce((r->>'ok')::boolean, false);
    v_latency := nullif(r->>'latency_ms', '')::integer;
    v_detail := left(coalesce(r->>'detail', ''), 300);

    insert into public.status_checks (service, ok, latency_ms, detail) values (v_service, v_ok, v_latency, v_detail);

    insert into public.status_daily (service, day, checks, ok_checks, latency_sum)
    values (v_service, v_day, 1, case when v_ok then 1 else 0 end, coalesce(v_latency, 0))
    on conflict (service, day) do update
      set checks = status_daily.checks + 1,
          ok_checks = status_daily.ok_checks + excluded.ok_checks,
          latency_sum = status_daily.latency_sum + excluded.latency_sum;

    select * into v_open from public.status_incidents where service = v_service and resolved_at is null;

    if v_ok then
      if v_open.id is not null then
        update public.status_incidents set resolved_at = now() where id = v_open.id;
        v_events := v_events || jsonb_build_object(
          'service', v_service, 'event', 'up',
          'started_at', v_open.started_at, 'resolved_at', now(), 'detail', v_open.detail);
      end if;
    elsif v_open.id is null then
      -- Die letzten p_fails Prüfungen anschauen: alle fehlgeschlagen?
      select count(*) filter (where not ok), min(checked_at)
        into v_recent_fails, v_first_fail
        from (select ok, checked_at from public.status_checks
              where service = v_service order by checked_at desc limit greatest(p_fails, 1)) last;
      if v_recent_fails >= greatest(p_fails, 1) then
        insert into public.status_incidents (service, started_at, detail) values (v_service, v_first_fail, v_detail);
        v_events := v_events || jsonb_build_object(
          'service', v_service, 'event', 'down', 'started_at', v_first_fail, 'detail', v_detail);
      end if;
    end if;
  end loop;

  -- Aufräumen, etwa einmal pro Stunde
  if extract(minute from now()) = 7 then
    delete from public.status_checks where checked_at < now() - interval '14 days';
    delete from public.status_daily where day < v_day - 120;
  end if;

  return v_events;
end;
$$;

revoke all on function public.status_secret_ok(text) from public;
revoke all on function public.status_bot_secret(text) from public;
revoke all on function public.record_status_run(text, jsonb, integer) from public;
grant execute on function public.status_secret_ok(text) to anon, authenticated;
grant execute on function public.status_bot_secret(text) to anon, authenticated;
grant execute on function public.record_status_run(text, jsonb, integer) to anon, authenticated;

-- ─────────────────────────────────────────────
-- Jede Minute prüfen
-- ─────────────────────────────────────────────

select cron.schedule(
  'aracle-status',
  '* * * * *',
  $cron$
    select net.http_post(
      url := 'https://aracle.ch/api/status/run',
      headers := jsonb_build_object(
        'content-type', 'application/json',
        'x-status-secret', (select value from public.bot_secrets where key = 'status_cron')
      ),
      body := '{}'::jsonb,
      timeout_milliseconds := 25000
    );
  $cron$
);
